import { getStorage, ref, uploadBytes, getDownloadURL } from 'firebase/storage';
import { v4 as uuidv4 } from 'uuid';

export interface ResponsiveImageUrls {
  original: string;
  large: string;   // 1200px
  medium: string;  // 600px
  small: string;   // 300px
  webp?: {
    large: string;   // 1200px WebP
    medium: string;  // 600px WebP
    small: string;   // 300px WebP
  };
}

/**
 * Enhanced image upload service that works with Firebase Extensions Resize Images
 * 
 * SETUP REQUIREMENTS:
 * 1. Install Firebase Extension "Resize Images" in your Firebase project
 * 2. Configure the extension with these settings:
 *    - Cloud Storage bucket: your-project.appspot.com
 *    - Sizes of resized images: 1200x1200,600x600,300x300
 *    - Deletion of original file: No
 *    - Convert to WebP: Yes
 *    - Cache control header: max-age=31536000
 */
export class ResponsiveImageService {
  private static readonly RESIZE_SIZES = {
    large: 1200,
    medium: 600,
    small: 300
  };

  /**
   * Upload image and get responsive URLs
   * Note: Resized images are generated asynchronously by Firebase Extension
   */
  static async uploadProductImage(
    file: File,
    vendorId: string,
    productTitle?: string
  ): Promise<ResponsiveImageUrls> {
    if (!file) {
      throw new Error('No file provided');
    }

    // Validate file type
    if (!this.isValidImageFile(file)) {
      throw new Error('Invalid image file. Supported formats: JPG, PNG, WebP, GIF');
    }

    // Validate file size (max 10MB for processing)
    if (file.size > 10 * 1024 * 1024) {
      throw new Error('Image file too large. Maximum size: 10MB');
    }

    try {
      const storage = getStorage();
      
      // Generate unique filename with optional product title
      const timestamp = Date.now();
      const fileExtension = this.getFileExtension(file);
      const sanitizedTitle = productTitle 
        ? this.sanitizeFilename(productTitle)
        : 'product';
      
      const fileName = `${timestamp}_${sanitizedTitle}.${fileExtension}`;
      const storagePath = `product-images/${vendorId}/${fileName}`;
      const storageRef = ref(storage, storagePath);
      
      // Upload original image
      await uploadBytes(storageRef, file);
      const originalUrl = await getDownloadURL(storageRef);
      
      // Generate URLs for resized versions
      // Note: These files will be created by Firebase Extension asynchronously
      const baseUrl = originalUrl.split('?')[0]; // Remove query parameters
      const basePath = baseUrl.substring(0, baseUrl.lastIndexOf('.'));
      const extension = this.getFileExtension(file);
      
      const responsiveUrls: ResponsiveImageUrls = {
        original: originalUrl,
        large: `${basePath}_1200x1200.${extension}`,
        medium: `${basePath}_600x600.${extension}`,
        small: `${basePath}_300x300.${extension}`,
        webp: {
          large: `${basePath}_1200x1200.webp`,
          medium: `${basePath}_600x600.webp`,
          small: `${basePath}_300x300.webp`
        }
      };

      console.log('Image uploaded successfully. Responsive versions will be generated by Firebase Extension.');
      return responsiveUrls;
    } catch (error) {
      console.error('Error uploading image:', error);
      throw error;
    }
  }

  /**
   * Update existing product image upload
   */
  static async uploadFile(
    file: File, 
    path: string = 'product-images',
    metadata?: { vendorId?: string; productTitle?: string }
  ): Promise<string> {
    if (metadata?.vendorId) {
      // Use responsive upload for product images
      const responsiveUrls = await this.uploadProductImage(
        file, 
        metadata.vendorId, 
        metadata.productTitle
      );
      return responsiveUrls.original;
    }

    // Fallback to simple upload for non-product images
    return this.simpleUpload(file, path);
  }

  /**
   * Simple upload for non-product images
   */
  private static async simpleUpload(file: File, path: string): Promise<string> {
    const storage = getStorage();
    const fileExtension = file.name.split('.').pop();
    const fileName = `${uuidv4()}.${fileExtension}`;
    const storageRef = ref(storage, `${path}/${fileName}`);
    
    await uploadBytes(storageRef, file);
    return await getDownloadURL(storageRef);
  }

  /**
   * Check if URL exists (for checking if resized images are ready)
   */
  static async checkImageExists(url: string): Promise<boolean> {
    try {
      const response = await fetch(url, { method: 'HEAD' });
      return response.ok;
    } catch {
      return false;
    }
  }

  /**
   * Wait for resized images to be generated
   */
  static async waitForResizedImages(
    responsiveUrls: ResponsiveImageUrls, 
    timeoutMs: number = 30000
  ): Promise<ResponsiveImageUrls> {
    const startTime = Date.now();
    
    while (Date.now() - startTime < timeoutMs) {
      // Check if at least the small version is ready
      const smallReady = await this.checkImageExists(responsiveUrls.small);
      
      if (smallReady) {
        console.log('Resized images are ready');
        return responsiveUrls;
      }
      
      // Wait 2 seconds before checking again
      await new Promise(resolve => setTimeout(resolve, 2000));
    }
    
    console.warn('Resized images not ready after timeout, using original');
    return responsiveUrls;
  }

  /**
   * Generate srcset string for responsive images
   */
  static generateSrcSet(responsiveUrls: ResponsiveImageUrls, useWebP: boolean = true): string {
    if (!responsiveUrls) return '';

    if (useWebP && responsiveUrls.webp) {
      return [
        `${responsiveUrls.webp.small} 300w`,
        `${responsiveUrls.webp.medium} 600w`,
        `${responsiveUrls.webp.large} 1200w`
      ].join(', ');
    }

    return [
      `${responsiveUrls.small} 300w`,
      `${responsiveUrls.medium} 600w`,
      `${responsiveUrls.large} 1200w`
    ].join(', ');
  }

  /**
   * Generate sizes attribute for responsive images
   */
  static generateSizes(breakpoints?: { mobile?: number; tablet?: number }): string {
    const mobile = breakpoints?.mobile || 640;
    const tablet = breakpoints?.tablet || 1024;

    return [
      `(max-width: ${mobile}px) 100vw`,
      `(max-width: ${tablet}px) 50vw`,
      '33vw'
    ].join(', ');
  }

  /**
   * Parse stored image URL to responsive URLs
   * For backward compatibility with existing products
   */
  static parseStoredImageUrl(imageUrl: string): ResponsiveImageUrls | null {
    if (!imageUrl) return null;

    try {
      const baseUrl = imageUrl.split('?')[0];
      const lastDotIndex = baseUrl.lastIndexOf('.');
      
      if (lastDotIndex === -1) return null;
      
      const basePath = baseUrl.substring(0, lastDotIndex);
      const extension = baseUrl.substring(lastDotIndex + 1);
      
      return {
        original: imageUrl,
        large: `${basePath}_1200x1200.${extension}`,
        medium: `${basePath}_600x600.${extension}`,
        small: `${basePath}_300x300.${extension}`,
        webp: {
          large: `${basePath}_1200x1200.webp`,
          medium: `${basePath}_600x600.webp`,
          small: `${basePath}_300x300.webp`
        }
      };
    } catch (error) {
      console.error('Error parsing image URL:', error);
      return null;
    }
  }

  /**
   * Validate image file type
   */
  private static isValidImageFile(file: File): boolean {
    const validTypes = ['image/jpeg', 'image/jpg', 'image/png', 'image/webp', 'image/gif'];
    return validTypes.includes(file.type.toLowerCase());
  }

  /**
   * Get file extension from file
   */
  private static getFileExtension(file: File): string {
    const extension = file.name.split('.').pop()?.toLowerCase();
    
    // Map MIME types to extensions for consistency
    const mimeToExt: Record<string, string> = {
      'image/jpeg': 'jpg',
      'image/jpg': 'jpg',
      'image/png': 'png',
      'image/webp': 'webp',
      'image/gif': 'gif'
    };
    
    return mimeToExt[file.type.toLowerCase()] || extension || 'jpg';
  }

  /**
   * Sanitize filename for storage
   */
  private static sanitizeFilename(filename: string): string {
    return filename
      .toLowerCase()
      .replace(/[^a-z0-9]/g, '_')
      .replace(/_+/g, '_')
      .substring(0, 50);
  }

  /**
   * Get optimal image URL based on container width
   */
  static getOptimalImage(
    responsiveUrls: ResponsiveImageUrls, 
    containerWidth: number,
    preferWebP: boolean = true
  ): string {
    if (!responsiveUrls) return '';

    let imageUrl: string;

    if (containerWidth <= 300) {
      imageUrl = preferWebP && responsiveUrls.webp 
        ? responsiveUrls.webp.small 
        : responsiveUrls.small;
    } else if (containerWidth <= 600) {
      imageUrl = preferWebP && responsiveUrls.webp 
        ? responsiveUrls.webp.medium 
        : responsiveUrls.medium;
    } else {
      imageUrl = preferWebP && responsiveUrls.webp 
        ? responsiveUrls.webp.large 
        : responsiveUrls.large;
    }

    return imageUrl || responsiveUrls.original;
  }
}

// Backward compatibility export
export const uploadFile = ResponsiveImageService.uploadFile;
